    private void carregarUsuaris() {

        jComboBoxUsuari.removeAllItems();

        for (Usuari usuari : businessLogic.getUsuaris()) {
            jComboBoxUsuari.addItem(usuari.getNomComplet());
        }

        jButtonEliminar.setEnabled(jComboBoxUsuari.getItemCount() > 0);
    }
    
    private void jButtonEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEliminarActionPerformed
        int index = jComboBoxUsuari.getSelectedIndex();

        if (index == -1) {
            JOptionPane.showMessageDialog(this, "Has de seleccionar un usuari.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Usuari usuari = businessLogic.getUsuaris().get(index);

        int resposta = JOptionPane.showConfirmDialog(this, "Segur que vols eliminar l'usuari " + usuari.getNomComplet() + "?", "Confirmar eliminació", JOptionPane.YES_NO_OPTION);

        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            businessLogic.borrarUsuari(usuari);

            JOptionPane.showMessageDialog(this, "Usuari eliminat correctament.", "Informació", JOptionPane.INFORMATION_MESSAGE);

            carregarUsuaris();

        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButtonEliminarActionPerformed

