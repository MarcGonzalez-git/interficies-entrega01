    private void carregarJocs() {

        jComboBoxJoc.removeAllItems();

        for (Joc joc : businessLogic.getJocs()) {
            jComboBoxJoc.addItem(joc.getNom());
        }

        jButtonEliminar.setEnabled(jComboBoxJoc.getItemCount() > 0);
    }
    
    private void jButtonEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEliminarActionPerformed
        int index = jComboBoxJoc.getSelectedIndex();

        if (index == -1) {
            JOptionPane.showMessageDialog(this, "Has de seleccionar un joc.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Joc joc = businessLogic.getJocs().get(index);

        int resposta = JOptionPane.showConfirmDialog(this, "Segur que vols eliminar el joc " + joc.getNom() + "?", "Confirmar eliminació", JOptionPane.YES_NO_OPTION);

        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            businessLogic.borrarJoc(joc);

            JOptionPane.showMessageDialog(this, "Joc eliminat correctament.", "Informació", JOptionPane.INFORMATION_MESSAGE);

            carregarJocs();

        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButtonEliminarActionPerformed

